"""
DAI Legal Model - Synthetic Benchmark Demo
IMPORTANT: Generates synthetic demonstration data only.
It does NOT connect to Qdrant, Core API, Model API, MCP, or hardware.
Run: python benchmark_demo.py
"""
import csv
import json
import random
from datetime import datetime, timezone
from pathlib import Path

SEED = 20261111
OUT = Path(__file__).resolve().parent
CONFIG = {
    "project": "Digital AI Intelligence (DAI) - DAI Legal Model",
    "cpu": "Intel Core i5-14600KF",
    "gpu": "NVIDIA GeForce RTX 4070 12GB",
    "ram": "32GB DDR4",
    "llm": "Qwen 2.5-7B Instruct",
    "embedding": "BGE-M3",
    "reranker": "BGE Reranker",
    "vector_database": "Qdrant",
    "backend": "FastAPI",
}
SCENARIOS = [
    ("embedding_generation", "Embedding generation", "ms", 18, 55),
    ("vector_search", "Qdrant vector search", "ms", 8, 35),
    ("reranking", "BGE reranking", "ms", 25, 90),
    ("llm_first_token", "LLM time to first token", "ms", 450, 1600),
    ("llm_generation", "LLM generation (short response)", "s", 2.0, 8.0),
    ("mcp_lookup", "MCP/DVC lookup", "s", 0.5, 3.5),
    ("api_end_to_end", "End-to-end API response", "s", 3.0, 12.0),
]

def build_results():
    rng = random.Random(SEED)
    results = []
    for key, label, unit, low, high in SCENARIOS:
        values = sorted(round(rng.uniform(low, high), 3) for _ in range(20))
        results.append({
            "metric": key, "label": label, "unit": unit, "sample_count": 20,
            "synthetic_mean": round(sum(values) / len(values), 3),
            "synthetic_min": values[0], "synthetic_max": values[-1],
            "synthetic_p95": values[-1],
            "status": "SYNTHETIC_DEMO_NOT_MEASURED",
        })
    return {
        "project": CONFIG["project"],
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "data_classification": "SYNTHETIC_DEMO_NOT_MEASURED",
        "notice": "Synthetic illustrative values only. No DAI services or hardware were benchmarked.",
        "system_configuration_reference": CONFIG,
        "method": {
            "samples_per_metric": 20, "random_seed": SEED, "mode": "simulation",
            "limitations": [
                "No connection to Qdrant, FastAPI, Model API, MCP, or DVC.",
                "No CPU, GPU VRAM, or RAM telemetry was collected.",
                "No model tokens-per-second measurement was performed.",
                "Values must not be presented as actual system performance."
            ]
        },
        "results": results,
    }

def write_outputs(data):
    (OUT / "benchmark_results.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    with (OUT / "benchmark_results.csv").open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(data["results"][0].keys()))
        writer.writeheader()
        writer.writerows(data["results"])

    lines = [
        "# DAI Legal Model - System Benchmark (Simulation Demo)", "",
        "> **SYNTHETIC / SIMULATED DATA.** This report is a software demonstration.",
        "> No live DAI service, model, database, or hardware was benchmarked.",
        "> Do not interpret these values as actual performance.", "",
        "## 1. Reference environment", "",
    ]
    for key, value in data["system_configuration_reference"].items():
        if key != "project":
            lines.append(f"- **{key.replace('_', ' ').title()}:** {value}")
    lines += ["", "## 2. Simulation methodology", "",
              "- 20 synthetic samples per metric.",
              f"- Fixed random seed: `{SEED}` for reproducibility.",
              "- Values are illustrative ranges generated by this script.",
              "- No network requests or service calls are made.", "",
              "## 3. Synthetic results", "",
              "| Metric | Unit | Samples | Mean | Min | Max | P95 |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for r in data["results"]:
        lines.append(
            f"| {r['label']} | {r['unit']} | {r['sample_count']} | "
            f"{r['synthetic_mean']} | {r['synthetic_min']} | "
            f"{r['synthetic_max']} | {r['synthetic_p95']} |"
        )
    lines += [
        "", "## 4. Limitations", "",
        "- These are not measured latency or throughput results.",
        "- No CPU, GPU VRAM, RAM, utilization, error-rate, or tokens/s telemetry was collected.",
        "- MCP/DVC values do not indicate endpoint availability or real fallback success.",
        "- Do not use these values for capacity planning or performance claims.",
        "", "## 5. Next step for real benchmarking", "",
        "When the environment is operational, replace this simulation with live tests",
        "that record latency, throughput, resource utilization, error rate, and retrieval quality.",
        "", "## 6. Reproduce the demo", "", "```bash",
        "python benchmark_demo.py", "```", "",
        "Classification: `SYNTHETIC_DEMO_NOT_MEASURED`", ""
    ]
    (OUT / "SYSTEM_BENCHMARK_DEMO.md").write_text("\n".join(lines), encoding="utf-8")

if __name__ == "__main__":
    write_outputs(build_results())
    print("Generated synthetic benchmark demo files.")
    print("NOTICE: Values are simulated, not measured system results.")
